List<String> citiesForIndiaState(String? state) {
  final name = normalizeStateName(state);
  if (name.isEmpty) return const [];
  return List<String>.from(indiaCitiesByState[name] ?? const <String>[]);
}

String resolveIndiaCityName(String? city, String? state) {
  final raw = (city ?? '').trim();
  if (raw.isEmpty) return '';
  final cities = citiesForIndiaState(state);
  for (final item in cities) {
    if (item.toLowerCase() == raw.toLowerCase()) return item;
  }
  return raw;
}

List<String> indiaStateOptionsIncluding(String? current) {
  final options = List<String>.from(indiaStateNames);
  final value = normalizeStateName(current);
  if (value.isNotEmpty &&
      !options.any((item) => item.toLowerCase() == value.toLowerCase())) {
    options.insert(0, value);
  }
  return options;
}

List<String> indiaCityOptionsIncluding(String? state, String? current) {
  final options = citiesForIndiaState(state);
  final value = (current ?? '').trim();
  if (value.isNotEmpty &&
      !options.any((item) => item.toLowerCase() == value.toLowerCase())) {
    options.insert(0, value);
  }
  return options;
}

bool cityBelongsToState(String? city, String? state) {
  final raw = (city ?? '').trim();
  if (raw.isEmpty) return true;
  return citiesForIndiaState(state)
      .any((item) => item.toLowerCase() == raw.toLowerCase());
}
